// Drives one live build through the real UI and screenshots each stage.
// node scripts/walk-live.mjs http://127.0.0.1:3110 [width height tag]
import { chromium } from "@playwright/test";
import { mkdirSync } from "node:fs";
const [base, w = "1440", h = "900", tag = "desk"] = process.argv.slice(2);
mkdirSync("artifacts/shots", { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: Number(w), height: Number(h) } });
page.on("pageerror", (e) => console.log("pageerror", e.message));
const shot = (n) => page.screenshot({ path: `artifacts/shots/live-${n}-${tag}.png` });
await page.goto(base + "/", { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Shop orders/ }).click();
await page.getByRole("button", { name: /Total sales by item/ }).click();
await page.getByRole("button", { name: /^Forge it$/ }).click();
await page.waitForURL(/\/forge\/b_/);
console.log("build", page.url());
await page.waitForTimeout(1200);
await shot("1-understand");
await page.waitForFunction(() => /writing|testing/i.test(document.body.innerText), null, { timeout: 60000 }).catch(() => {});
await page.waitForTimeout(1500);
await shot("2-draft");
await page.getByText("Permission passport").waitFor({ timeout: 180000 });
await page.getByRole("tab", { name: "preview" }).click();
await page.waitForTimeout(600);
const firstResult = page.locator("table").nth(1).locator("tbody tr").first();
await firstResult.click().catch(() => {});
await page.waitForTimeout(500);
await shot("3-preview");
await page.getByRole("tab", { name: "approve" }).click();
await page.waitForTimeout(500);
await shot("4-approve");
const seal = page.getByRole("button", { name: /Hold to approve/ });
const box = await seal.boundingBox();
await page.mouse.move(box.x + 40, box.y + 40);
await page.mouse.down();
await page.waitForTimeout(1600);
await page.mouse.up();
await page.getByText("Installed").first().waitFor({ timeout: 20000 });
await page.waitForTimeout(1000);
await shot("5-installed");
await page.getByRole("link", { name: "Run it" }).click();
await page.waitForURL(/\/tools\//);
await page.getByRole("button", { name: /^Run$/ }).click();
await page.getByText(/Run finished|Already handled/).waitFor({ timeout: 20000 });
await shot("6-run");
await page.getByRole("tab", { name: "X-ray" }).click();
await page.waitForTimeout(2500);
await page.locator("ol button").nth(2).click().catch(() => {});
await page.waitForTimeout(500);
await shot("7-xray");
console.log("tool", page.url());
await browser.close();
