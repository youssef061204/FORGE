/**
 * Regenerates the numbers block in README.md from committed result files,
 * so the prose cannot drift from the data.  npx tsx scripts/readme-numbers.ts
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { latest, legacyBaseline } from "../src/server/results";

const pct = (x: number) => `${Math.round(x * 1000) / 10}%`;
const s = (ms: number | null) => (ms === null ? "—" : `${(ms / 1000).toFixed(1)} s`);
const dev = latest("dev")?.summary;
const val = latest("validation")?.summary;
const legacy = legacyBaseline();
const holdoutPath = "evaluation/results/holdout-latest.json";
const holdout = existsSync(holdoutPath) ? JSON.parse(readFileSync(holdoutPath, "utf8")) : undefined;

const rows: string[] = ["| Set | Result | 95% interval | Median time to preview | Source |", "| --- | --- | --- | --- | --- |"];
if (val) rows.push(`| Validation (71, held out) | **${val.passed} of ${val.n} (${pct(val.passRate)})** | ${pct(val.interval95[0])}–${pct(val.interval95[1])} | ${s(val.timeToPreviewP50Ms)} | \`evaluation/results/${latest("validation")!.dir}/validation.json\` |`);
if (dev) rows.push(`| Development (18) | ${dev.passed} of ${dev.n} (${pct(dev.passRate)}) | ${pct(dev.interval95[0])}–${pct(dev.interval95[1])} | ${s(dev.timeToPreviewP50Ms)} | \`evaluation/results/${latest("dev")!.dir}/dev.json\` |`);
if (legacy) rows.push(`| Development, before FORGE 2 | ${legacy.summary.passed} of ${legacy.summary.recorded} | — | ${s(legacy.summary.p50Ms)} per mission | \`evaluation/results/2026-11-17-c8b172f-legacy-baseline/result.json\` |`);
if (holdout) rows.push(`| Sealed holdout (one run) | ${holdout.headline} | ${holdout.interval ?? "—"} | ${holdout.ttp ?? "—"} | \`${holdout.source}\` |`);
const extra: string[] = [];
if (val) extra.push(`Validation detail: ${val.decisions ? `${val.decisions.correct} of ${val.decisions.n} connect/clarify/unsupported decisions correct; ` : ""}${val.verifiedFalseSuccess} verified-but-wrong results; p95 time to preview ${s(val.timeToPreviewP95Ms)}. Model ${val.model} on ${val.hardware}, commit ${val.commit}.`);
const block = ["<!-- numbers:start (generated by scripts/readme-numbers.ts; do not edit by hand) -->", ...rows, "", ...extra, "<!-- numbers:end -->"].join("\n");
const readme = readFileSync("README.md", "utf8");
const next = readme.replace(/<!-- numbers:start[\s\S]*?<!-- numbers:end -->/, block);
writeFileSync("README.md", next);
console.log(block);
